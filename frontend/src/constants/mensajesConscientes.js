export function obtenerMensajeConsciente(score) {
  let categoria;
  
  if (score >= 91) categoria = 'EXCELENTE';
  else if (score >= 76) categoria = 'MUY_BUENA';
  else if (score >= 61) categoria = 'SOLIDA';
  else if (score >= 46) categoria = 'EQUILIBRADA';
  else if (score >= 31) categoria = 'DESAFIANTE';
  else if (score >= 16) categoria = 'RESILIENTE';
  else categoria = 'TRANSFORMADORA';
  
  const mensajes = MENSAJES_CONSCIENTES[categoria];
  const mensajeAleatorio = mensajes[Math.floor(Math.random() * mensajes.length)];
  
  return {
    categoria: getCategoriaLabel(categoria),
    ...mensajeAleatorio
  };
}

function getCategoriaLabel(categoria) {
  const labels = {
    'EXCELENTE': 'Ruta Excelente',
    'MUY_BUENA': 'Ruta Muy Buena',
    'SOLIDA': 'Ruta Sólida',
    'EQUILIBRADA': 'Ruta Equilibrada',
    'DESAFIANTE': 'Ruta Desafiante',
    'RESILIENTE': 'Ruta Resiliente',
    'TRANSFORMADORA': 'Ruta Transformadora'
  };
  return labels[categoria] || 'Ruta';
}

export function getIconForScore(score) {
  if (score >= 91) return '🌟';
  if (score >= 76) return '✨';
  if (score >= 61) return '💪';
  if (score >= 46) return '⚖️';
  if (score >= 31) return '🔥';
  if (score >= 16) return '🧘';
  return '🌱';
}

